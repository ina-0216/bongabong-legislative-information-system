#!/usr/bin/env node
/**
 * Generates a translator checklist from src/context/LanguageContext.jsx.
 *
 * Keys whose tl value is null fall back to English at runtime and are listed
 * here. The draft Tagalog strings are listed separately so a reviewer can tell
 * machine-independent drafts from work still outstanding.
 *
 * Run: node scripts/generate-translation-checklist.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const SRC = 'src/context/LanguageContext.jsx';
const OUT = join('docs', 'translation-checklist.md');

const source = readFileSync(SRC, 'utf8');

const enStart = source.indexOf('en: {');
const tlStart = source.indexOf('tl: {');
if (enStart < 0 || tlStart < 0) {
  console.error('Could not locate the en/tl blocks in', SRC);
  process.exit(1);
}

const enBlock = source.slice(enStart, tlStart);
const tlBlock = source.slice(tlStart, source.indexOf('function LANG_STATUS'));

const enEntries = new Map();
for (const m of enBlock.matchAll(/^ {4}([A-Za-z][A-Za-z0-9]*):\s*'((?:[^'\\]|\\.)*)'/gm)) {
  enEntries.set(m[1], m[2]);
}

const tlEntries = new Map();
for (const m of tlBlock.matchAll(/^ {4}([A-Za-z][A-Za-z0-9]*):\s*(null|'((?:[^'\\]|\\.)*)')/gm)) {
  tlEntries.set(m[1], m[3] === undefined ? null : m[3]);
}

const pending = [...enEntries.keys()].filter((k) => tlEntries.get(k) === null);
const drafted = [...enEntries.keys()].filter((k) => tlEntries.get(k) !== null && tlEntries.get(k) !== undefined);
const missing = [...enEntries.keys()].filter((k) => !tlEntries.has(k));

const esc = (s) => String(s).replace(/\|/g, '\\|');

let md = `# Translation checklist

Generated by \`node scripts/generate-translation-checklist.mjs\` from \`${SRC}\`.
Do not hand-edit: regenerate after changing the translation object.

## How the fallback works

\`t(key)\` returns \`translations[language][key]\`, and if that is \`null\` it
returns the English string. A \`null\` Tagalog value therefore renders English
rather than a guess. This is deliberate: unofficial Tagalog for civic and
legal copy would misrepresent the municipality's voice.

## Coverage

| Bucket | Count |
| --- | --- |
| Total keys | ${enEntries.size} |
| Tagalog drafted (needs review) | ${drafted.length} |
| Tagalog outstanding | ${pending.length} |
| Missing a tl entry entirely | ${missing.length} |

Keys pending: ${pending.length > 0 ? `${Math.round((drafted.length / enEntries.size) * 100)}% drafted, ${Math.round((pending.length / enEntries.size) * 100)}% outstanding` : 'n/a'}

## Outstanding — awaiting a Tagalog translator

Fill the \`tl\` value for each key. Leave \`null\` until it is properly translated.

| Key | English source |
| --- | --- |
${pending.map((k) => `| \`${k}\` | ${esc(enEntries.get(k))} |`).join('\n')}

## Drafted — requires municipal review before use

These have Tagalog values but **no municipal translator has reviewed them**.
Confirm terminology, especially for official legal vocabulary.

| Key | English | Current Tagalog (draft) |
| --- | --- | --- |
${drafted.map((k) => `| \`${k}\` | ${esc(enEntries.get(k))} | ${esc(tlEntries.get(k))} |`).join('\n')}
`;

if (missing.length) {
  md += `\n## Keys with no tl entry\n\n${missing.map((k) => `- \`${k}\``).join('\n')}\n`;
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md, 'utf8');

console.log(`Wrote ${OUT}`);
console.log(`  total ${enEntries.size}, drafted ${drafted.length}, outstanding ${pending.length}, missing ${missing.length}`);